"""Slice a 20 mm cube with a built slicing-service image, as the build workflow does before publishing it.

Starts nothing itself: point it at a running container. It takes OrcaSlicer's own Bambu Lab X1 Carbon
profiles from the same OrcaSlicer release, flattened the way the farm's engine sends profiles, and checks the
answer is G-code that this version of OrcaSlicer wrote.

  python3 slicer/smoke.py http://localhost:3000 2.5.0
"""

import json
import sys
import urllib.parse
import urllib.request
import uuid

PROFILES = "https://raw.githubusercontent.com/OrcaSlicer/OrcaSlicer/v{version}/resources/profiles/BBL/"
CHOSEN = (
    ("machine", "Bambu Lab X1 Carbon 0.4 nozzle", "printerProfile"),
    ("process", "0.20mm Standard @BBL X1C", "presetProfile"),
    ("filament", "Bambu PLA Basic @BBL X1C", "filamentProfile"),
)


def cube(size: int = 20) -> bytes:
    v = [(x, y, z) for z in (0, size) for y in (0, size) for x in (0, size)]
    v = [v[0], v[1], v[3], v[2], v[4], v[5], v[7], v[6]]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]  # fmt: skip
    out = ["solid cube"]
    for face in faces:
        out += ["facet normal 0 0 0", "outer loop"]
        out += ["vertex %d %d %d" % v[i] for i in face]
        out += ["endloop", "endfacet"]
    return ("\n".join(out + ["endsolid cube"]) + "\n").encode()


def profile(version: str, kind: str, name: str) -> dict:
    url = PROFILES.format(version=version) + kind + "/" + urllib.parse.quote(name) + ".json"
    data = json.load(urllib.request.urlopen(url, timeout=30))
    base = profile(version, kind, data["inherits"]) if data.get("inherits") else {}
    merged = {**base, **data}
    merged.pop("inherits", None)
    merged.pop("instantiation", None)
    merged["from"] = "User"
    return merged


def main(service: str, version: str) -> int:
    boundary = uuid.uuid4().hex
    parts = [("file", "cube.stl", "model/stl", cube())]
    for kind, name, field in CHOSEN:
        parts.append((field, field + ".json", "application/json", json.dumps(profile(version, kind, name)).encode()))
    body = b""
    for field, filename, ctype, payload in parts:
        body += (
            f'--{boundary}\r\nContent-Disposition: form-data; name="{field}"; filename="{filename}"\r\n'
            f"Content-Type: {ctype}\r\n\r\n"
        ).encode() + payload + b"\r\n"
    body += f"--{boundary}--\r\n".encode()
    request = urllib.request.Request(
        service.rstrip("/") + "/slice", data=body, method="POST",
        headers={"Content-Type": f"multipart/form-data; boundary={boundary}"},
    )  # fmt: skip
    with urllib.request.urlopen(request, timeout=300) as answer:
        gcode = answer.read().decode(errors="replace")
    header = next((line for line in gcode.splitlines()[:5] if "generated by" in line), "")
    moves = sum(1 for line in gcode.splitlines() if line.startswith("G1 "))
    print(header.strip(), f"({moves} moves)")
    if f"OrcaSlicer {version}" not in header or moves < 100:
        print(f"expected G-code from OrcaSlicer {version}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
